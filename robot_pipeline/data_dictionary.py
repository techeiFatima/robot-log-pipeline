"""Generate docs/data_dictionary.md from the dbt docs and the live database.

Column descriptions come from the dbt YAML files (via dbt/target/manifest.json)
and column types from DuckDB, so the dictionary cannot drift from the code.
Tables outside dbt (raw, audit, stream) are described here.

    python -m robot_pipeline.dbt_runner build      # refreshes manifest.json
    python -m robot_pipeline.data_dictionary       # rewrites docs/data_dictionary.md
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import duckdb

from robot_pipeline import config
from robot_pipeline.loader import EXPECTED_COLUMNS

RAW_DESCRIPTIONS = {
    "Num": "Row counter within the file, 1-based.",
    "Timestamp": 'Log time as text, ISO 8601 ending in "Z" (UTC); '
    "863 values wrapped in stray quotes.",
    "Temperature_T0": "Temperature, probably joint 0 "
    "(breaks the Temperature_J1..J5 naming; unconfirmed).",
    "Tool_current": "Tool (gripper) current.",
    "cycle ": "Robot cycle number (the column name has a trailing space).",
    "Robot_ProtectiveStop": "1 = robot stopped itself for safety, 0 = no stop, "
    "empty = unknown (54 rows).",
    "grip_lost": "True when the gripper lost its grip.",
    "source_file": "Added by the loader: name of the file the row came from.",
    "loaded_at": "Added by the loader: when the row was stored (UTC).",
}
for _j in range(6):
    RAW_DESCRIPTIONS.setdefault(
        f"Current_J{_j}", f"Joint {_j} current (can be negative; unconfirmed meaning)."
    )
    RAW_DESCRIPTIONS.setdefault(
        f"Speed_J{_j}", f"Joint {_j} speed (can be negative; unconfirmed meaning)."
    )
    if _j:
        RAW_DESCRIPTIONS.setdefault(f"Temperature_J{_j}", f"Joint {_j} temperature.")

OTHER_TABLES = {
    "raw_logs": (
        "cobot.duckdb",
        "The source file exactly as delivered, plus two loader columns.",
        RAW_DESCRIPTIONS,
    ),
    "load_audit": (
        "cobot.duckdb",
        "One row per file per loader run.",
        {
            "source_file": "File name.",
            "sha256": "Checksum of the file's bytes.",
            "rows_loaded": "Rows of this file in raw_logs after the run.",
            "rows_replaced": "Rows deleted and re-inserted for this file in this run.",
            "loaded_at": "Time of the run (UTC).",
            "action": "loaded (new file), replaced (changed content), reloaded (same "
            "content rewritten, e.g. --force), unchanged (skipped). "
            "Only loaded/replaced count as new data.",
        },
    ),
}

EXTRA_PATH = config.PROJECT_ROOT / "docs" / "_data_dictionary_extra.md"  # stream tables, files


def _types(con, table: str) -> dict[str, str]:
    rows = con.execute(
        "SELECT column_name, data_type FROM information_schema.columns "
        "WHERE table_name = ? ORDER BY ordinal_position",
        [table],
    ).fetchall()
    return dict(rows)


def _table_md(name: str, where: str, description: str, cols: dict[str, str], types: dict) -> str:
    lines = [
        f"### `{name}`",
        "",
        f"*{where}.* {description}",
        "",
        "| Column | Type | Meaning |",
        "|---|---|---|",
    ]
    for col, typ in types.items():
        shown = col.replace(" ", "␠") if col.endswith(" ") else col
        lines.append(f"| `{shown}` | {typ} | {cols.get(col, '')} |")
    return "\n".join(lines) + "\n"


def build(db_path: Path, manifest_path: Path) -> str:
    manifest = json.loads(manifest_path.read_text())
    models = sorted(
        (n for n in manifest["nodes"].values() if n["resource_type"] == "model"),
        key=lambda n: (
            ["staging", "intermediate", "marts", "ml"].index(n["fqn"][1]) * 100 + len(n["name"])
        ),
    )
    con = duckdb.connect(str(db_path), read_only=True)
    try:
        parts = [
            "# Data dictionary",
            "",
            "Generated by `python -m robot_pipeline.data_dictionary` from the dbt docs and the",
            "database; do not edit by hand. The data is the public UR3 CobotOps dataset (UCI),",
            "standing in for real robot logs. Times are UTC. `␠` marks a trailing space.",
            "",
            "## Loader tables (`cobot.duckdb`)",
            "",
        ]
        for name, (where, desc, cols) in OTHER_TABLES.items():
            parts.append(_table_md(name, where, desc, cols, _types(con, name)))
        parts += ["## dbt models (`cobot.duckdb`)", ""]
        staging = next(m for m in models if m["name"] == "stg_robot_logs")
        inherited = {c: v.get("description", "") for c, v in staging["columns"].items()}
        for m in models:
            layer = m["fqn"][1]
            mat = m["config"]["materialized"]
            # Columns passed through unchanged keep the staging description.
            cols = {**inherited, **{c: v.get("description", "") for c, v in m["columns"].items()}}
            desc = " ".join(m.get("description", "").split())
            parts.append(_table_md(m["name"], f"{layer} {mat}", desc, cols, _types(con, m["name"])))
    finally:
        con.close()
    parts.append(EXTRA_PATH.read_text())
    assert set(RAW_DESCRIPTIONS) >= set(EXPECTED_COLUMNS)
    return "\n".join(parts)


def main() -> int:
    out = config.PROJECT_ROOT / "docs" / "data_dictionary.md"
    out.write_text(
        build(config.db_path(), config.PROJECT_ROOT / "dbt" / "target" / "manifest.json")
    )
    print(f"Wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
